#!/bin/sh
# ctx — agent interface for repository-external workspace records.
# POSIX sh + awk/grep/sed only. Layout per ~/.agents/skills/workspace-context/SKILL.md
#
#   ctx id|dir|init|status|check|index|facts|skills|active|find|show|add|set|migrate|help
set -u

AGENTS_HOME="${AGENTS_HOME:-$HOME/.agents}"
WS_ROOT="$AGENTS_HOME/workspaces"
MAX_CHARS="${CTX_MAX_CHARS:-3000}"
MAX_LINES="${CTX_MAX_LINES:-40}"
TYPES="decision checkpoint evidence blocker fact history"
STATUSES="current superseded deferred resolved disputed"
# brevity caps (Unicode chars). Body = everything after the frontmatter. 0 = unlimited.
LINE_MAX="${CTX_LINE_MAX:-160}"          # per physical line in CONTEXT.md
TITLE_MAX="${CTX_TITLE_MAX:-80}"
body_cap() { case "$1" in fact) echo "${CTX_FACT_MAX:-300}";; blocker) echo "${CTX_BLOCKER_MAX:-400}";;
  checkpoint) echo "${CTX_CHECKPOINT_MAX:-600}";; decision) echo "${CTX_DECISION_MAX:-800}";; *) echo 0;; esac; }

die() { printf 'ctx: %s\n' "$*" >&2; exit 1; }

# ---- path / identity -------------------------------------------------------
canon() {  # canonical real path of a directory
  ( CDPATH= cd -- "$1" 2>/dev/null && pwd -P ) || die "not a directory: $1"
}
root_of() {  # git toplevel if inside a repo, else the folder itself
  p=$(canon "${1:-.}")
  top=$(git -C "$p" rev-parse --show-toplevel 2>/dev/null || true)
  [ -n "$top" ] && p=$(canon "$top")
  printf '%s\n' "$p"
}
sha16() {
  if command -v shasum >/dev/null 2>&1; then printf '%s' "$1" | shasum -a 256 | cut -c1-16
  else printf '%s' "$1" | sha256sum | cut -c1-16; fi
}
ws_id() {
  p=$(root_of "${1:-.}")
  base=$(basename "$p" | tr 'A-Z' 'a-z' | sed 's/[^a-z0-9]/-/g; s/--*/-/g; s/^-//; s/-$//')
  printf '%s-%s\n' "$base" "$(sha16 "$p")"
}
ws_dir() { printf '%s/%s\n' "$WS_ROOT" "$(ws_id "${1:-.}")"; }

# resolve workspace dir from an optional path argument; sets W
resolve() { W=$(ws_dir "${1:-.}"); [ -d "$W" ] || die "no workspace at $W (run: ctx init)"; }

# ---- measurement -------------------------------------------------------------
chars_of() { LC_ALL=C tr -d '\200-\277' < "$1" | wc -c | tr -d ' '; }   # Unicode scalar count
lines_of() { wc -l < "$1" | tr -d ' '; }
strlen() { printf '%s' "$1" | LC_ALL=C tr -d '\200-\277' | wc -c | tr -d ' '; }
body_of() { awk 'NR==1&&$0=="---"{f=1;next} f==1&&$0=="---"{f=2;next} f==2{print}' "$1"; }
body_chars() { body_of "$1" | LC_ALL=C tr -d '\200-\277' | wc -c | tr -d ' '; }

# ---- frontmatter -------------------------------------------------------------
fm() {  # fm <file> <key>
  awk -v k="$2" 'NR==1&&$0!="---"{exit} NR>1&&$0=="---"{exit} NR>1{i=index($0,":"); if(i&&substr($0,1,i-1)==k){v=substr($0,i+1); sub(/^ +/,"",v); print v; exit}}' "$1"
}
set_fm() {  # set_fm <file> <key> <value>
  awk -v k="$2" -v v="$3" 'BEGIN{infm=0;done=0} NR==1&&$0=="---"{infm=1;print;next}
    infm&&$0=="---"{ if(!done){print k": "v}; infm=0; print; next }
    infm{ i=index($0,":"); if(i&&substr($0,1,i-1)==k){print k": "v; done=1; next} }
    {print}' "$1" > "$1.tmp" && mv "$1.tmp" "$1"
}

# ---- index ---------------------------------------------------------------------
records_sorted() {  # record files ordered by sequence number (filenames contain no spaces)
  ls "$W"/records/*.md 2>/dev/null | awk -F/ '{n=$NF; sub(/^[A-Z]-/,"",n); sub(/-.*/,"",n); print n+0, $0}' | sort -n | cut -d' ' -f2-
}
gen_index() {  # print INDEX.md for workspace $W
  printf '# Records index — %s\n\n' "$(basename "$W")"
  printf 'Generated by `ctx index`; one line per record in `records/`. Grep this file, then `ctx show <id>`. Never bulk-read `records/`.\n\n'
  printf '| id | type | status | created | title | tags | read-when |\n|---|---|---|---|---|---|---|\n'
  for rf in $(records_sorted); do
    printf '| %s | %s | %s | %s | %s | %s | %s |\n' \
      "$(fm "$rf" id)" "$(fm "$rf" type)" "$(fm "$rf" status)" "$(fm "$rf" created)" \
      "$(fm "$rf" title)" "$(fm "$rf" tags)" "$(fm "$rf" read-when)"
  done
}
gen_facts() {  # derived FACTS.md view: every current/deferred/disputed fact record
  printf '# Facts — %s\n\nGenerated by `ctx index` from `records/F-*.md`; do not edit. Reusable stable facts only.\n\n' "$(basename "$W")"
  for rf in $(records_sorted); do
    [ "$(fm "$rf" type)" = fact ] || continue; st=$(fm "$rf" status); [ "$st" = superseded ] && continue
    printf -- '- %s [%s] %s — %s\n' "$(fm "$rf" id)" "$st" "$(fm "$rf" title)" "$(body_of "$rf" | awk 'NF{print; exit}')"
  done
}
has_facts() { ls "$W"/records/F-*.md >/dev/null 2>&1; }
reindex() { gen_index > "$W/INDEX.md"; if has_facts; then gen_facts > "$W/FACTS.md"; fi; }
list_skills() {  # local skills: name<TAB>description
  for sk in "$W"/skills/*/SKILL.md; do [ -e "$sk" ] || break
    printf '%s\t%s\n' "$(fm "$sk" name)" "$(fm "$sk" description)"; done
}

next_id() {  # next zero-padded sequence number across all records
  n=$(ls "$W"/records 2>/dev/null | sed -n 's/^[A-Z]-\([0-9][0-9]*\)-.*/\1/p' | sort -n | tail -1 | sed 's/^0*//')
  printf '%04d\n' $(( ${n:-0} + 1 ))
}
type_prefix() {
  case "$1" in decision) echo D;; checkpoint) echo C;; evidence) echo E;; blocker) echo B;; fact) echo F;; history) echo H;;
    *) die "type must be one of: $TYPES";; esac
}
slug() { printf '%s' "$1" | tr 'A-Z' 'a-z' | sed 's/[^a-z0-9]/-/g; s/--*/-/g; s/^-//; s/-$//' | cut -c1-48 | sed 's/-$//'; }
today() { date +%Y-%m-%d; }

context_template() {
  cat <<TPL
# $(basename "$W")

## Identity
- Path: \`$1\`
- Kind: $2

## Objective
- (one line: what this workspace is for right now)

## Constraints
- (scope limits, negative constraints, active authority, deferred user choices)

## State
- (phase, owner/session, last checkpoint id)

## Blockers
- none

## Next
- (single next resume action)

## Records
- (status=current/deferred records only, one line each: \`<id> <title> — read when <trigger>\`; everything else via INDEX.md)

## Skills
- (local skills in skills/<name>/SKILL.md, one line each: \`<name> — load when <trigger>\`; none if empty)
TPL
}

# ---- commands --------------------------------------------------------------------
cmd_init() {
  p=$(root_of "${1:-.}"); W="$WS_ROOT/$(ws_id "$p")"
  kind="folder"; git -C "$p" rev-parse --show-toplevel >/dev/null 2>&1 && kind="git repository"
  mkdir -p "$W/records" "$W/artifacts/plans"
  [ -e "$W/CONTEXT.md" ] || context_template "$p" "$kind" > "$W/CONTEXT.md"
  reindex; printf '%s\n' "$W"
}
cmd_status() {
  resolve "${1:-.}"; c="$W/CONTEXT.md"; [ -f "$c" ] || die "missing $c"
  ch=$(chars_of "$c"); ln=$(lines_of "$c"); rc=$(ls "$W"/records 2>/dev/null | grep -c '\.md$' || true)
  printf 'workspace: %s\nCONTEXT.md: %s chars (max %s), %s lines (max %s)\nrecords: %s\n' "$W" "$ch" "$MAX_CHARS" "$ln" "$MAX_LINES" "$rc"
  [ -e "$W/FACTS.md" ] && { if has_facts; then printf 'FACTS.md: generated from %s fact records\n' "$(ls "$W"/records/F-*.md | wc -l | tr -d ' ')"; else printf 'FACTS.md: legacy hand-written (see: ctx migrate)\n'; fi; }
  n=$(list_skills | wc -l | tr -d ' '); [ "$n" -gt 0 ] && printf 'local skills: %s (ctx skills)\n' "$n"
  ls "$W"/DETAIL.*.md >/dev/null 2>&1 && printf 'legacy: DETAIL.*.md present (see: ctx migrate)\n'
  if [ "$ch" -gt "$MAX_CHARS" ] || [ "$ln" -gt "$MAX_LINES" ]; then printf 'OVER CAP — demote history into records/ before writing more.\n'; return 1; fi
  printf 'ok\n'
}
cmd_check() {
  resolve "${1:-.}"; fail=0
  cmd_status "${1:-.}" >/dev/null 2>&1 || { echo "FAIL: CONTEXT.md over cap ($(chars_of "$W/CONTEXT.md") chars / $(lines_of "$W/CONTEXT.md") lines)"; fail=1; }
  for h in Identity Objective Constraints State Blockers Next Records Skills; do
    grep -q "^## $h\$" "$W/CONTEXT.md" || { echo "FAIL: CONTEXT.md missing section '## $h'"; fail=1; }
  done
  ln=0; while IFS= read -r l; do ln=$((ln+1)); [ "$(strlen "$l")" -le "$LINE_MAX" ] || { echo "FAIL: CONTEXT.md line $ln exceeds $LINE_MAX chars"; fail=1; }; done < "$W/CONTEXT.md"
  for sk in $(sed -n 's/^- \([a-z0-9][a-z0-9-]*\) — .*/\1/p' "$W/CONTEXT.md"); do
    [ -f "$W/skills/$sk/SKILL.md" ] || { echo "FAIL: CONTEXT.md lists local skill '$sk' but skills/$sk/SKILL.md is missing"; fail=1; }
  done
  for sk in "$W"/skills/*/SKILL.md; do [ -e "$sk" ] || break; n=$(fm "$sk" name)
    [ "$n" = "$(basename "$(dirname "$sk")")" ] || { echo "FAIL: $sk frontmatter name '$n' != folder name"; fail=1; }
    grep -q "^- $n — " "$W/CONTEXT.md" || { echo "FAIL: local skill '$n' not listed under ## Skills in CONTEXT.md"; fail=1; }
  done
  seen=""
  for f in $(records_sorted); do
    id=$(fm "$f" id); ty=$(fm "$f" type); st=$(fm "$f" status); ti=$(fm "$f" title)
    [ -n "$id" ] && [ -n "$ty" ] && [ -n "$st" ] && [ -n "$ti" ] || { echo "FAIL: $f lacks id/type/status/title"; fail=1; }
    case " $TYPES " in *" $ty "*) ;; *) echo "FAIL: $f bad type '$ty'"; fail=1;; esac
    case " $STATUSES " in *" $st "*) ;; *) echo "FAIL: $f bad status '$st'"; fail=1;; esac
    case "$(basename "$f")" in "$id"-*) ;; *) echo "FAIL: $f filename does not start with id '$id'"; fail=1;; esac
    [ "$(strlen "$ti")" -le "$TITLE_MAX" ] || { echo "FAIL: $id title exceeds $TITLE_MAX chars"; fail=1; }
    cap=$(body_cap "$ty"); case ",$(fm "$f" tags | tr -d ' ')," in *,legacy,*) cap=0;; esac; [ "$cap" -eq 0 ] || [ "$(body_chars "$f")" -le "$cap" ] || { echo "FAIL: $id ($ty) body exceeds $cap chars — split or demote detail into an evidence/history record"; fail=1; }
    case " $seen " in *" $id "*) echo "FAIL: duplicate id $id"; fail=1;; esac; seen="$seen $id"
    tail -c1 "$f" | od -An -c | grep -q '\\n' || { echo "FAIL: $f lacks final newline"; fail=1; }
  done
  if [ -f "$W/INDEX.md" ]; then gen_index | cmp -s - "$W/INDEX.md" || { echo "FAIL: INDEX.md stale (run: ctx index)"; fail=1; }
  else echo "FAIL: INDEX.md missing"; fail=1; fi
  if has_facts; then gen_facts | cmp -s - "$W/FACTS.md" 2>/dev/null || { echo "FAIL: FACTS.md stale or hand-edited (run: ctx index)"; fail=1; }; fi
  for id in $(sed -n 's/^- \([A-Z]-[0-9][0-9]*\).*/\1/p' "$W/CONTEXT.md"); do
    ls "$W"/records/"$id"-*.md >/dev/null 2>&1 || { echo "FAIL: CONTEXT.md references unknown record $id"; fail=1; }
  done
  [ "$fail" -eq 0 ] && echo "ok: $W"; return $fail
}
cmd_index() { resolve "${1:-.}"; reindex; printf '%s/INDEX.md\n' "$W"; has_facts && printf '%s/FACTS.md\n' "$W"; true; }
cmd_facts() { resolve "${1:-.}"; has_facts && gen_facts | sed -n '5,$p'; true; }
cmd_skills() { resolve "${1:-.}"; list_skills; }
cmd_active() { resolve "${1:-.}"; grep -E '^\| [A-Z]-[0-9]+ \| [a-z]+ \| (current|deferred) \|' "$W/INDEX.md" || true; }
cmd_find() { [ $# -ge 1 ] || die "usage: ctx find <regex> [path]"; resolve "${2:-.}"; grep -iE -- "$1" "$W/INDEX.md" | grep '^| [A-Z]-' || true; }
cmd_show() { [ $# -ge 1 ] || die "usage: ctx show <id> [path]"; resolve "${2:-.}"
  f=$(ls "$W"/records/"$1"-*.md 2>/dev/null | head -1); [ -n "$f" ] || die "no record $1"; cat "$f"; }
cmd_add() {
  # ctx add <type> <title> [-t tags] [-r read-when] [-s supersedes] [path]   (body from stdin when piped)
  [ $# -ge 2 ] || die "usage: ctx add <type> <title> [-t tags] [-r read-when] [-s id] [path]"
  ty=$1; ti=$2; shift 2; tags=""; rw=""; sup=""; path="."
  while [ $# -gt 0 ]; do case "$1" in
    -t) tags=$2; shift 2;; -r) rw=$2; shift 2;; -s) sup=$2; shift 2;; *) path=$1; shift;; esac; done
  resolve "$path"; pre=$(type_prefix "$ty"); id="$pre-$(next_id)"; f="$W/records/$id-$(slug "$ti").md"
  [ "$(strlen "$ti")" -le "$TITLE_MAX" ] || die "title exceeds $TITLE_MAX chars"
  if [ -t 0 ]; then body=""; else body=$(cat); fi
  cap=$(body_cap "$ty"); [ "$cap" -eq 0 ] || [ "$(strlen "$body")" -le "$cap" ] || die "$ty body exceeds $cap chars — keep the conclusion here; put detail in an evidence record"
  { printf -- '---\nid: %s\ntype: %s\nstatus: current\ntitle: %s\ntags: %s\ncreated: %s\n' "$id" "$ty" "$ti" "$tags" "$(today)"
    [ -n "$rw" ] && printf 'read-when: %s\n' "$rw"; [ -n "$sup" ] && printf 'supersedes: %s\n' "$sup"
    printf -- '---\n\n'
    printf '%s\n' "${body:-(body)}"
  } > "$f"
  [ -n "$sup" ] && { s=$(ls "$W"/records/"$sup"-*.md 2>/dev/null | head -1); [ -n "$s" ] && set_fm "$s" status superseded; }
  reindex; printf '%s\n' "$f"
}
cmd_set() {  # ctx set <id> <key> <value> [path]
  [ $# -ge 3 ] || die "usage: ctx set <id> <key> <value> [path]"; resolve "${4:-.}"
  f=$(ls "$W"/records/"$1"-*.md 2>/dev/null | head -1); [ -n "$f" ] || die "no record $1"
  [ "$2" = status ] && case " $STATUSES " in *" $3 "*) ;; *) die "status must be one of: $STATUSES";; esac
  set_fm "$f" "$2" "$3"; reindex; printf '%s\n' "$f"
}
cmd_migrate() {
  # Lossless legacy conversion: old CONTEXT.md and DETAIL.*.md become history records; a fresh CONTEXT.md skeleton is written.
  resolve "${1:-.}"; mkdir -p "$W/records"
  [ -f "$W/CONTEXT.md" ] && ! grep -q '^## Records$' "$W/CONTEXT.md" || die "nothing to migrate (already in records layout)"
  path=$(grep -o '`/[^`]*`' "$W/CONTEXT.md" | head -1 | tr -d '`')
  id="H-$(next_id)"; f="$W/records/$id-legacy-context.md"
  { printf -- '---\nid: %s\ntype: history\nstatus: superseded\ntitle: Legacy CONTEXT.md before records migration\ntags: legacy, migration\ncreated: %s\nread-when: auditing decisions or evidence recorded before the records layout\n---\n\n' "$id" "$(today)"
    cat "$W/CONTEXT.md"; } > "$f"
  tail -n +11 "$f" | cmp -s - "$W/CONTEXT.md" || die "legacy copy mismatch; aborting before any removal"
  for d in "$W"/DETAIL.*.md; do
    [ -e "$d" ] || break
    v=$(basename "$d" .md | sed 's/^DETAIL\.//'); id="H-$(next_id)"; nf="$W/records/$id-$(slug "$v").md"
    { printf -- '---\nid: %s\ntype: history\nstatus: superseded\ntitle: %s\ntags: legacy, detail\ncreated: %s\nread-when: the former Detail Index trigger for %s applies\n---\n\n' "$id" "$v" "$(today)" "$v"
      cat "$d"; } > "$nf" && tail -n +11 "$nf" | cmp -s - "$d" && rm "$d"
  done
  if [ -f "$W/FACTS.md" ] && grep -qE '^- Statement:|\*\*Statement:\*\*|^\| FACT-' "$W/FACTS.md"; then
    tmpd="$W/records/.facts-split.$$"; mkdir -p "$tmpd"
    # Normalize every legacy ledger form into "### ID — title" + "- Key: value" blocks, one file per fact:
    #  (a) "## ID" or "### ID — title" heading followed by "- Statement:" bullets
    #  (b) one-line "- **Fact ID:** `X`; **Status:** `s`; **Statement:** ..." entries
    #  (c) table rows "| ID | Statement | Scope | Source | Freshness | Status |"
    awk -v d="$tmpd" '
      function trim(x){gsub(/^[ \t]+|[ \t]+$/,"",x); return x}
      function start(){n++; f=sprintf("%s/%03d",d,n)}
      /^\*\*Fact ID:\*\*|^- \*\*Fact ID:\*\*/ { start(); line=$0; gsub(/^- /,"",line); m=split(line,parts,/; \*\*/); id=""; st="";
          for(i=1;i<=m;i++){kv=parts[i]; gsub(/\*\*/,"",kv); gsub(/`/,"",kv); k=kv; sub(/:.*/,"",k); v=kv; sub(/^[^:]*: */,"",v);
            if(k=="Fact ID") id=v; else if(k=="Status") st=v; else if(k=="Statement") stt=v; else rest=rest "- " k ": " v "\n"}
          printf "### %s — %s\n- Statement: %s\n%s- Status: %s\n",id,id,stt,rest,st > f; rest=""; next }
      /^\| FACT-/ { start(); m=split($0,c,"|"); for(i=1;i<=m;i++) c[i]=trim(c[i]);
          printf "### %s — %s\n- Statement: %s\n- Scope: %s\n- Source or evidence: %s\n- Freshness or expiry: %s\n- Status: %s\n",c[2],c[2],c[3],c[4],c[5],c[6],c[7] > f; next }
      /^##+ / { h=$0; sub(/^##+ /,"",h); pend=h; next }
      /^- Statement:/ { if(pend!=""){ start(); t=pend; if(t !~ / — /) t=t " — " t; printf "### %s\n",t > f; pend="" } }
      f && /^- / { print > f }
    ' "$W/FACTS.md"
    for part in "$tmpd"/*; do
      ti=$(sed -n '1s/^### [^ ]* — //p' "$part"); st=$(sed -n 's/^- Status: *`*\([a-z]*\)`*.*/\1/p' "$part" | head -1)
      case " $STATUSES " in *" ${st:-x} "*) ;; *) st=current;; esac
      id="F-$(next_id)"; nf="$W/records/$id-$(slug "$ti").md"
      { printf -- '---\nid: %s\ntype: fact\nstatus: %s\ntitle: %s\ntags: legacy\ncreated: %s\n---\n\n' "$id" "$st" "$ti" "$(today)"
        sed -n 's/^- Statement: //p' "$part" | head -1; printf '\n'; sed '1d' "$part" | sed '/^- Statement: /d'; } > "$nf"
    done
    rm -rf "$tmpd"; id="H-$(next_id)"; nf="$W/records/$id-legacy-facts.md"
    { printf -- '---\nid: %s\ntype: history\nstatus: superseded\ntitle: Legacy hand-written FACTS.md\ntags: legacy, facts\ncreated: %s\nread-when: checking the original wording of a migrated fact\n---\n\n' "$id" "$(today)"; cat "$W/FACTS.md"; } > "$nf"
    tail -n +11 "$nf" | cmp -s - "$W/FACTS.md" && rm "$W/FACTS.md"
  fi
  mkdir -p "$W/artifacts"
  for d in "$W"/*/; do d=${d%/}; case "$(basename "$d")" in records|skills|artifacts) ;; *) mv "$d" "$W/artifacts/";; esac; done
  kind="unknown"; [ -d "$path" ] && { kind="folder"; git -C "$path" rev-parse --show-toplevel >/dev/null 2>&1 && kind="git repository"; }
  context_template "${path:-unknown}" "$kind" > "$W/CONTEXT.md"
  printf -- '- Migrated from legacy layout on %s; hot state must be rebuilt from %s (see INDEX.md)\n' "$(today)" "$(basename "$f" .md | cut -d- -f1-2)" >> "$W/CONTEXT.md"
  reindex; printf 'migrated: %s\n' "$W"; ls "$W/records"
}
cmd_help() { sed -n '2,5p' "$0" | sed 's/^# \{0,1\}//'; cat <<'H'

  ctx id [path]                 workspace id for path (default: cwd, git toplevel if in a repo)
  ctx dir [path]                workspace directory
  ctx init [path]               create workspace skeleton (CONTEXT.md, INDEX.md, records/, artifacts/plans/)
  ctx status [path]             size/cap report; exit 1 when CONTEXT.md is over cap
  ctx check [path]              validate layout, frontmatter, ids, index freshness, links
  ctx index [path]              regenerate INDEX.md (and FACTS.md when fact records exist)
  ctx facts [path]              print current facts (derived from records/F-*.md)
  ctx skills [path]             list local skills (skills/<name>/SKILL.md) as name<TAB>description
  ctx active [path]             index lines with status current|deferred
  ctx find <regex> [path]       grep INDEX.md (id, type, status, title, tags, read-when)
  ctx show <id> [path]          print one record
  ctx add <type> <title> [-t tags] [-r read-when] [-s supersedes-id] [path]   body from stdin
                                types: decision checkpoint evidence blocker fact history
                                body caps: fact 300, blocker 400, checkpoint 600, decision 800 chars; title 80
  ctx set <id> <key> <value> [path]   update one frontmatter key (e.g. status resolved)
  ctx migrate [path]            lossless legacy → records conversion (CONTEXT.md, DETAIL.*.md, FACTS.md; other dirs → artifacts/)
  env: AGENTS_HOME, CTX_MAX_CHARS (3000), CTX_MAX_LINES (40), CTX_LINE_MAX (160), CTX_TITLE_MAX (80),
       CTX_FACT_MAX, CTX_BLOCKER_MAX, CTX_CHECKPOINT_MAX, CTX_DECISION_MAX
H
}

cmd=${1:-help}; [ $# -gt 0 ] && shift
case "$cmd" in
  id) ws_id "${1:-.}";; dir) ws_dir "${1:-.}";; init) cmd_init "$@";; status) cmd_status "$@";;
  check) cmd_check "$@";; index) cmd_index "$@";; active) cmd_active "$@";; find) cmd_find "$@";;
  facts) cmd_facts "$@";; skills) cmd_skills "$@";;
  show) cmd_show "$@";; add) cmd_add "$@";; set) cmd_set "$@";; migrate) cmd_migrate "$@";;
  help|-h|--help) cmd_help;; *) die "unknown command '$cmd' (try: ctx help)";;
esac
